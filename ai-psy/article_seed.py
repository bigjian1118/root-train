# 内置文章 id 前缀：保证稳定且不与未来自增 id 冲突
_SEED_ID_PREFIX = "seed"


def seed_articles(conn):
    """幂等写入/刷新内置文章：按稳定 seed id 对齐，已存在的内置文章会刷新为最新正文。

    仅对系统内置的 seed 前缀文章进行插入或更新，绝不触碰历史手工文章；
    created_at 首次插入时生成并保留，避免刷新正文后打乱列表排序。

    conn：已连接并建好表结构的 sqlite 连接（row_factory 需可用）。
    返回本次写入/更新的条数。
    """
    import time

    now = int(time.time() * 1000)  # 毫秒（articles.created_at 统一存毫秒）
    inserted = 0
    updated = 0
    for i, art in enumerate(BUILTIN_ARTICLES):
        # 用递增偏移制造不同的发布时间（每条相差 1 秒），展示时按新旧排序效果更自然
        created_at = now - (len(BUILTIN_ARTICLES) - i) * 1000
        art_id = f"{_SEED_ID_PREFIX}-{(i + 1):03d}"
        exists = conn.execute(
            "SELECT created_at FROM articles WHERE id=?", (art_id,)
        ).fetchone()
        if exists is None:
            conn.execute(
                "INSERT OR IGNORE INTO articles "
                "(id, cover, title, summary, content, is_active, created_at) "
                "VALUES (?, ?, ?, ?, ?, 1, ?)",
                (art_id, None, art["title"], art["summary"], art["content"], created_at),
            )
            inserted += 1
        else:
            # 仅同步内置文章的标题/简介/正文，保留原有发布时间与上架状态
            conn.execute(
                "UPDATE articles SET title=?, summary=?, content=? WHERE id=? "
                "AND is_active=1",
                (art["title"], art["summary"], art["content"], art_id),
            )
            updated += 1
    conn.commit()
    print(f"[articles] 内置科普文章：写入 {inserted} 篇，刷新 {updated} 篇")
    return inserted + updated
