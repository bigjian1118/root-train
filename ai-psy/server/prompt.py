def scenario_display_name(key: str) -> str:
    """场景键 -> 展示名：当前配置优先，其次旧版映射，最后原样返回。"""
    return SCENARIOS.get(key, {}).get("name", SCENARIO_NAME_LEGACY.get(key, key))


def crowd_tag_to_scenario(tag: str) -> str:
    """人群标签（中文）-> 场景键；旧数据存场景键则原样返回。"""
    return {v["name"]: k for k, v in SCENARIOS.items()}.get(tag, tag)
