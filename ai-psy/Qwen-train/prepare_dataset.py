# ==================== 工具函数 ====================
def _resolve_dataset_root() -> str:
    """
    确定数据集根目录：直接使用 config.DATASET_ROOT（autodl-fs/dataset）。
    config 已做自适应解析——真实 AutoDL 服务器指向 /root/autodl-fs/dataset，
    本地模拟服务器指向项目同级 autodl-fs/dataset；
    若目录不可创建 / 不可写（如纯本地开发无数据盘），回退脚本同级 output_dataset/。
    """
    local_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                             "output_dataset")
    try:
        os.makedirs(config.DATASET_ROOT, exist_ok=True)
        # 写探测文件确认目录可写
        probe = os.path.join(config.DATASET_ROOT, ".write_probe")
        with open(probe, "w", encoding="utf-8") as f:
            f.write("ok")
        os.remove(probe)
        return config.DATASET_ROOT
    except OSError:
        os.makedirs(local_dir, exist_ok=True)
        print(f"[提示] 无法写入 {config.DATASET_ROOT}，改用本地目录：{local_dir}")
        return local_dir


def _sub_dir(root: str, key: str) -> str:
    """在数据集根目录下创建并返回某子文件夹（当前仅 ai_chat）"""
    d = os.path.join(root, key)
    os.makedirs(d, exist_ok=True)
    return d


def _write_jsonl(records: list, path: str) -> None:
    """写出 jsonl 并校验每行可解析"""
    with open(path, "w", encoding="utf-8") as f:
        for r in records:
            line = json.dumps(r, ensure_ascii=False)
            json.loads(line)  # 自校验
            f.write(line + "\n")
    print(f"[输出] {path}: {len(records)} 条")


