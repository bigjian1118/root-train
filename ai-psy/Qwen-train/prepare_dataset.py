def build_question_bank() -> dict:
    """生成三人群 SCL-90 题库（90 题 × 3 人群：小学生 / 中学生 / 大学生）"""
    bank = {}
    idx_map = {"primary_student": 0, "junior_student": 1, "college_student": 2}
    for key, meta in SCENARIO_META.items():
        idx = idx_map[key]
        bank[key] = {
            "name": meta["name"],
            "questions": [
                {
                    "id": qid,
                    "factor": _QID_TO_FACTOR.get(qid, "其他"),
                    "question": SCENE_ITEMS[qid][idx],
                }
                for qid in range(1, 91)
            ],
        }
    return bank


# ==================== 2. AI 聊天微调素材（仅 ai_chat） ====================
def _sample(messages: list) -> dict:
    """封装为训练记录"""
    return {"messages": messages}


def build_chat_samples(scenario_key: str) -> list:
    """
    生成单人群聊天微调样本，三类：
      A 出题引导：把标准题转为人群场景题并给出作答指导（90 条）
      B 共情回应：用户报告某题选了偏重/严重后的安抚与维度科普（90 条）
      C 维度科普：因子含义解释（10 条）
    （原 D 类「场景化改写 JSON 输出」样本已随场景化文本测试训练一并移除）
    """
    meta = SCENARIO_META[scenario_key]
    idx_map = {"primary_student": 0, "junior_student": 1, "college_student": 2}
    idx = idx_map[scenario_key]
    sys_msg = {"role": "system", "content": meta["system"]}
    samples = []

    for qid in range(1, 91):
        std_text = QUESTIONS[qid]
        scene_text = SCENE_ITEMS[qid][idx]
        factor = _QID_TO_FACTOR.get(qid, "其他")

        # ---------- A 出题引导 ----------
        samples.append(_sample([
            sys_msg,
            {"role": "user",
             "content": f"请把 SCL-90 第{qid}题标准题「{std_text}」改写成适合{meta['name']}的生活场景题。"},
            {"role": "assistant",
             "content": f"「{scene_text}」\n请根据最近一周的实际情况，从"
                        f"「没有、很轻、中等、偏重、严重」五个选项中选一个最接近的。"
                        f"这道题想了解的是你的{factor}方面的状态。"},
        ]))

        # ---------- B 共情回应（随机选一个高分档） ----------
        score = random.choice([3, 4, 5])
        score_word = LIKERT_SCALE[score]
        comfort = {
            "primary_student": (
                f"谢谢你诚实地告诉我，选「{score_word}」需要很大的勇气。"
                f"有这种感觉的小朋友不是只有你一个，这不是你的错。"
                f"这个感觉和{FACTOR_BRIEF.get(factor, '')}有关。"
                "愿意和心语老师多说说吗？也可以告诉爸爸妈妈或你信任的老师，我们一起想办法。"
            ),
            "junior_student": (
                f"你选了「{score_word}」，愿意说出来就已经很勇敢了。"
                f"青春期的这些感受很真实，也并不丢人——它和{factor}维度有关："
                f"{FACTOR_BRIEF.get(factor, '')}。"
                "如果它已经影响到你的上课、睡觉或和同学相处，"
                "可以找信任的老师或家长聊聊，也可以随时和我继续说。"
            ),
            "college_student": (
                f"你选了「{score_word}」，说明这件事最近确实困扰到你了，谢谢你的坦诚。"
                f"它属于{factor}维度——{FACTOR_BRIEF.get(factor, '')}。"
                "这种状态在大学生里并不罕见，你不需要为此自责。"
                "如果持续影响生活，学校心理中心随时可以预约，我也可以陪你聊聊具体怎么缓解。"
            ),
        }[scenario_key]
        samples.append(_sample([
            sys_msg,
            {"role": "user", "content": f"我在回答「{scene_text}」这道题时，选了「{score_word}」。"},
            {"role": "assistant", "content": comfort},
        ]))

    # ---------- C 维度科普 ----------
    for factor, brief in FACTOR_BRIEF.items():
        samples.append(_sample([
            sys_msg,
            {"role": "user", "content": f"SCL-90 量表里的「{factor}」维度是什么意思？"},
            {"role": "assistant",
             "content": f"「{factor}」维度{brief}。在测评中，它由若干题目共同反映，"
                        "得分越高说明相关困扰越明显。分数只是参考，不代表诊断结果，"
                        "如果这个维度的得分让你担心，可以和我具体聊聊。"},
        ]))
    return samples


# ==================== 主流程 ====================
def main() -> None:
    random.seed(42)
    dataset_root = _resolve_dataset_root()

    # ---------- 1. 题库（dataset 根目录 + 网站 static/data 各一份） ----------
    bank = build_question_bank()
    bank_json = json.dumps(bank, ensure_ascii=False, indent=1)
    with open(os.path.join(dataset_root, "question_bank.json"), "w", encoding="utf-8") as f:
        f.write(bank_json)
    web_dir = os.path.join(_ROOT, "static", "data")
    os.makedirs(web_dir, exist_ok=True)
    with open(os.path.join(web_dir, "question_bank.json"), "w", encoding="utf-8") as f:
        f.write(bank_json)
    print(f"[输出] 题库已写入 {web_dir}{os.sep}question_bank.json（含 3 人群 × 90 题：小学生/中学生/大学生）")

    # ---------- 2. ai_chat 通用聊天微调数据库（三人群样本合并打乱 9:1 切分） ----------
    all_records = []
    for key in SCENARIO_META:
        recs = build_chat_samples(key)
        print(f"[样本] {key}（{SCENARIO_META[key]['name']}）：{len(recs)} 条")
        all_records.extend(recs)
    random.shuffle(all_records)
    n_val = max(1, int(len(all_records) * 0.1))
    val, train = all_records[:n_val], all_records[n_val:]
    chat_sub = _sub_dir(dataset_root, config.AI_CHAT_KEY)
    _write_jsonl(train, os.path.join(chat_sub, "train.jsonl"))
    _write_jsonl(val, os.path.join(chat_sub, "val.jsonl"))

    print(f"[完成] 三人群聊天样本共 {len(all_records)} 条（不再生成场景化文本测试训练数据）")
    print(f"       目录结构：{dataset_root}（仅 ai_chat + question_bank.json）")
    print("       下一步：bash train_all.sh 训练 ai_chat 通用聊天 LoRA")


if __name__ == "__main__":
    main()
