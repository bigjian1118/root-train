import { formatTimestamp } from '@/lib/utils';

const STATUS_MARK = '【状态分析】';
const PLAN_MARK = '【干预方案】';

interface InterventionResponse {
  ok?: boolean;
  student_name?: string;
  class?: string;
  status?: string;
  plan?: string;
  /** 兼容少数后端直接返回整段正文的字段名。 */
  ai_content?: string;
  content?: string;
  report?: string;
  generated_at?: number;
}

interface InterventionResult {
  studentName: string;
  className: string;
  status: string;
  plan: string;
  generatedAt?: number;
}

function pickArray<T>(raw: unknown, key: string): T[] {
  if (Array.isArray(raw)) {
    return raw as T[];
  }
  if (raw && typeof raw === 'object') {
    const record = raw as Record<string, unknown>;
    if (Array.isArray(record[key])) {
      return record[key] as T[];
    }
    if (Array.isArray(record.items)) {
      return record.items as T[];
    }
    if (Array.isArray(record.data)) {
      return record.data as T[];
    }
  }
  return [];
}

/** 后端正常会拆好 status/plan；若只返回整段正文，按固定标记前端再拆一次。 */
function normalizeIntervention(payload: InterventionResponse): InterventionResult {
  const wholeText = payload.ai_content || payload.content || payload.report || '';
  let status = payload.status || '';
  let plan = payload.plan || '';

  if (!status && !plan && wholeText) {
    const statusIndex = wholeText.indexOf(STATUS_MARK);
    const planIndex = wholeText.indexOf(PLAN_MARK);
    if (statusIndex >= 0 && planIndex > statusIndex) {
      status = wholeText.slice(statusIndex + STATUS_MARK.length, planIndex).trim();
      plan = wholeText.slice(planIndex + PLAN_MARK.length).trim();
    } else {
      plan = wholeText.trim();
    }
  } else if (!plan && wholeText) {
    plan = wholeText;
  }

  return {
    studentName: payload.student_name || '该学生',
    className: payload.class || '—',
    status,
    plan,
    generatedAt: payload.generated_at,
  };
}

/** 按学生去重，生成干预建议下拉选项。 */
function uniqueStudents(reports: TextReportSummary[]): TextReportSummary[] {
  const best = new Map<string, TextReportSummary>();
  reports.forEach((report) => {
    const key = report.student_id || report.student_name;
    const previous = best.get(key);
    if (!previous || (report.created_at ?? 0) >= (previous.created_at ?? 0)) {
      best.set(key, report);
    }
  });
  return Array.from(best.values()).sort((a, b) =>
    a.student_name.localeCompare(b.student_name, 'zh-CN'),
  );
}

function InterventionContent() {
  const searchParams = useSearchParams();
  const { toast } = useToast();
  const queryStudentId = (searchParams.get('student') || searchParams.get('student_id') || '').trim();

  const [classFilter, setClassFilter] = useState('');
  const [pickedStudentId, setPickedStudentId] = useState('');
  const [result, setResult] = useState<InterventionResult | null>(null);
  const [loading, setLoading] = useState(false);
  const [errorText, setErrorText] = useState('');
  const autoGeneratedRef = useRef('');

  const classesQuery = useQuery({
    queryKey: ['teacher', 'classes'],
    queryFn: async () =>
      pickArray<string>(await getJson<unknown>('/api/teacher/classes'), 'classes'),
    enabled: !queryStudentId,
  });

  const reportsQuery = useQuery({
    queryKey: ['teacher', 'reports', classFilter],
    queryFn: async () => {
      const query = classFilter ? `?class=${encodeURIComponent(classFilter)}` : '';
      return pickArray<TextReportSummary>(
        await getJson<unknown>(`/api/teacher/reports${query}`),
        'reports',
      );
    },
    enabled: !queryStudentId,
  });

  const students = useMemo(
    () => uniqueStudents(reportsQuery.data ?? []),
    [reportsQuery.data],
  );

  const generate = useCallback(
    async (studentId: string) => {
      if (!studentId) {
        return;
      }
      setLoading(true);
      setErrorText('');
      setResult(null);
      try {
        // 后端契约按 student_id 取该生最新文本 + 视频报告，不接受 report id 入参。
        const response = await postJson<InterventionResponse>('/api/ai/intervention', {
          student_id: studentId,
        });
        if (response.ok === false) {
          throw new Error('AI 服务暂时不可用，请稍后重试');
        }
        setResult(normalizeIntervention(response));
      } catch (error) {
        setErrorText(
          error instanceof ApiError
            ? error.message
            : error instanceof Error
              ? error.message
              : '网络异常，请稍后重试',
        );
      } finally {
        setLoading(false);
      }
    },
    [],
  );

  useEffect(() => {
    if (!queryStudentId || autoGeneratedRef.current === queryStudentId) {
      return;
    }
    autoGeneratedRef.current = queryStudentId;
    void generate(queryStudentId);
  }, [generate, queryStudentId]);

  const activeStudentId = queryStudentId || pickedStudentId;
  const displayName = result?.studentName || '该学生';
  const classLabel = result?.className || (classFilter || '全部班级');

  const plainText = result
    ? `${STATUS_MARK}\n${result.status || '（无状态分析）'}\n\n${PLAN_MARK}\n${
        result.plan || '（无干预方案正文）'
      }`
    : '';

  const handleCopy = async () => {
    if (!plainText) {
      return;
    }
    try {
      await navigator.clipboard.writeText(plainText);
      toast({ title: '已复制到剪贴板', variant: 'success' });
    } catch {
      toast({
        title: '复制失败',
        description: '浏览器未授予剪贴板权限，请手动选中文本复制',
        variant: 'destructive',
      });
    }
  };

  const handleExport = () => {
    if (!plainText) {
      return;
    }
    const blob = new Blob([plainText], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const anchor = document.createElement('a');
    anchor.href = url;
    anchor.download = `干预建议-${displayName}.txt`;
    anchor.click();
    URL.revokeObjectURL(url);
  };

  return (
    <AppShell
      role="teacher"
      pageClassName="mx-auto min-h-screen max-w-[980px] px-[24px] pb-[56px] pt-[20px]"
      headNavClassName="mb-[14px] flex flex-wrap items-center gap-[12px]"
    >
      {/* 旧版 intervention.html 标题口径：🤖 大标题 + 元信息行 */}
      <h1 className="aic-iv-h1">🤖 AI 综合干预建议</h1>
      <p className="aic-iv-meta">
        {displayName} · {classLabel}
        {result?.generatedAt ? ` · 生成于 ${formatTimestamp(result.generatedAt)}` : ''}
      </p>

      {/* 新增功能入口保持：从报告详情直达时可更换学生 */}
      {queryStudentId ? (
        <p className="mb-4">
          <Link
            href="/teacher/intervention"
            className="inline-flex h-10 items-center gap-2 rounded-pill border border-border px-4 text-sm font-medium transition-colors hover:bg-accent hover:text-accent-foreground"
          >
            更换学生
          </Link>
        </p>
      ) : null}

      {!queryStudentId ? (
        <Card className="mb-4">
          <CardHeader className="pb-3">
            <CardTitle className="flex items-center gap-2 text-base">
              <UserRound className="h-4 w-4 text-primary" />
              选择学生
            </CardTitle>
          </CardHeader>
          <CardContent className="flex flex-col gap-3 sm:flex-row sm:items-center">
            <Select
              value={classFilter}
              onChange={(event) => {
                setClassFilter(event.target.value);
                setPickedStudentId('');
              }}
              className="sm:max-w-[220px]"
              aria-label="选择班级"
            >
              <option value="">全部绑定班级</option>
              {(classesQuery.data ?? []).map((className) => (
                <option key={className} value={className}>
                  {className}
                </option>
              ))}
            </Select>
            <Select
              value={pickedStudentId}
              onChange={(event) => setPickedStudentId(event.target.value)}
              className="flex-1"
              aria-label="选择学生"
              disabled={reportsQuery.isLoading || students.length === 0}
            >
              <option value="">
                {reportsQuery.isLoading
                  ? '学生列表加载中…'
                  : students.length
                    ? '请选择学生'
                    : '暂无可选学生'}
              </option>
              {students.map((student) => (
                <option key={student.student_id} value={student.student_id}>
                  {student.student_name}（{student.student_id}）·{' '}
                  {student.class ?? student.student_class ?? '—'}
                </option>
              ))}
            </Select>
            <Button
              onClick={() => void generate(pickedStudentId)}
              disabled={!pickedStudentId || loading}
              className="shrink-0"
            >
              {loading ? <Loader2 className="h-4 w-4 animate-spin" /> : <Sparkles className="h-4 w-4" />}
              {loading ? '生成中…' : '生成干预建议'}
            </Button>
          </CardContent>
        </Card>
      ) : null}

      {!queryStudentId && reportsQuery.isLoading ? <LoadingSkeleton rows={2} /> : null}

      {!queryStudentId && !reportsQuery.isLoading && students.length === 0 ? (
        <EmptyState
          icon={<Lightbulb className="h-5 w-5" />}
          title="暂无可生成建议的学生"
          description="当前班级还没有学生提交测评报告，完成测评后才能生成干预建议。"
        />
      ) : null}

      {loading ? (
        <div className="aic-glass aic-iv-state">
          正在结合该生最新文本测评与视频情绪报告生成干预建议，请稍候…
        </div>
      ) : null}

      {!loading && errorText ? (
        <div className="aic-glass aic-iv-state error">
          <p>{errorText}</p>
          {activeStudentId ? (
            <button
              type="button"
              className="aic-btn aic-btn-ghost"
              style={{ marginTop: 14 }}
              onClick={() => void generate(activeStudentId)}
            >
              重新生成
            </button>
          ) : null}
        </div>
      ) : null}

      {!loading && result ? (
        <div className="space-y-4">
          <Card>
            <CardContent className="flex flex-col gap-3 p-4 sm:flex-row sm:items-center sm:justify-between">
              <div className="flex flex-wrap items-center gap-2">
                <span className="text-sm font-medium">{displayName}</span>
                <Badge variant="secondary">{classLabel}</Badge>
                {result.generatedAt ? (
                  <span className="text-xs text-muted-foreground">
                    生成于 {formatTimestamp(result.generatedAt)}
                  </span>
                ) : null}
              </div>
              <div className="flex flex-wrap gap-2">
                <Button size="sm" variant="outline" onClick={() => void handleCopy()}>
                  <ClipboardCopy className="h-3.5 w-3.5" />
                  复制
                </Button>
                <Button size="sm" variant="outline" onClick={handleExport}>
                  <Download className="h-3.5 w-3.5" />
                  导出文本
                </Button>
                <Button
                  size="sm"
                  onClick={() => void generate(activeStudentId)}
                  disabled={!activeStudentId}
                >
                  <RefreshCw className="h-3.5 w-3.5" />
                  重新生成
                </Button>
              </div>
            </CardContent>
          </Card>

          {/* 旧版模块一：简要状态分析（文案与结构 1:1） */}
          <section className="aic-glass aic-iv-card">
            <h2>
              <span className="aic-txt-hl">一、简要状态分析</span>
            </h2>
            <div className="aic-iv-status">
              {result.status ? (
                <MarkdownText content={result.status} />
              ) : (
                <p className="text-sm text-muted-foreground">本次生成未返回状态分析，请以下方干预方案为准。</p>
              )}
            </div>
          </section>

          {/* 旧版模块二：具体干预方案（发光描边强调） */}
          <section className="aic-glass aic-iv-card aic-iv-plan-card">
            <h2>
              <span className="aic-txt-hl">二、具体干预方案</span>
            </h2>
            <div className="aic-iv-status">
              {result.plan ? (
                <MarkdownText content={result.plan} />
              ) : (
                <p className="text-sm text-muted-foreground">未返回干预方案正文。</p>
              )}
            </div>
          </section>

          {/* 旧版底部统一免责声明（文案一字不差） */}
          <p className="aic-iv-disclaimer">
            ⚠️ 本页内容由 AI 辅助生成，仅供教师沟通指导参考，不能替代专业心理诊断与治疗。如有持续困扰，建议寻求专业心理咨询师帮助。
          </p>
        </div>
      ) : null}
    </AppShell>
  );
}

export default function TeacherInterventionPage() {
  return (
    <AuthGuard role="teacher">
      {/* useSearchParams 在 App Router 静态渲染时必须位于 Suspense 边界内。 */}
      <Suspense fallback={<LoadingSkeleton rows={3} />}>
        <InterventionContent />
      </Suspense>
    </AuthGuard>
  );
}
